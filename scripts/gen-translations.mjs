// scripts/gen-translations.mjs
// Generate supabase/seed_translations.sql from every curated batch in
// src/content/i18n/*.i18n.ts. For each { en, ur, roman } entry, emit two upsert
// rows into `translations` — target `ur` and `ur-roman` — keyed by the SAME hash
// the Edge /translate route computes: sha256(target_lang + '|' + source_text).
//
// Run:  node scripts/gen-translations.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'src', 'content', 'i18n')
const outPath = join(root, 'supabase', 'seed_translations.sql')

const sha256 = (s) => createHash('sha256').update(s, 'utf8').digest('hex')
const sqlStr = (s) => "'" + String(s).replace(/'/g, "''") + "'"

// Each entry is a single object literal { en: '…', ur: '…', roman: '…' } with
// single-quoted values that contain no straight apostrophes.
const re = /\{ en: '([\s\S]*?)', ur: '([\s\S]*?)', roman: '([\s\S]*?)' \}/g

const files = readdirSync(dir).filter((f) => f.endsWith('.i18n.ts')).sort()
if (!files.length) {
  console.error('No *.i18n.ts files in ' + dir)
  process.exit(1)
}

// hash -> row. Dedupe so a repeated (target, en) never appears twice in one
// INSERT (Postgres ON CONFLICT cannot touch the same row twice). Last wins.
const byHash = new Map()
const perFile = []

for (const f of files) {
  const text = readFileSync(join(dir, f), 'utf8')
  let count = 0
  let m
  while ((m = re.exec(text)) !== null) {
    const [, en, ur, roman] = m
    for (const [target, tr] of [['ur', ur], ['ur-roman', roman]]) {
      const hash = sha256(target + '|' + en)
      byHash.set(hash, { hash, target, en, tr })
    }
    count++
  }
  perFile.push(`${f}: ${count} entries`)
}

const rows = [...byHash.values()]
const values = rows
  .map((r) => `  (${sqlStr(r.hash)}, ${sqlStr(r.target)}, ${sqlStr(r.en)}, ${sqlStr(r.tr)})`)
  .join(',\n')

const sql = `-- supabase/seed_translations.sql
-- GENERATED by scripts/gen-translations.mjs — do not edit by hand.
-- Curated Urdu + Roman-Urdu wording. Paste into the Supabase SQL editor
-- (or: supabase db execute < supabase/seed_translations.sql).
-- Idempotent: re-running updates the wording for existing hashes.
-- Sources: ${files.join(', ')}
insert into translations (hash, target_lang, source_text, translated_text) values
${values}
on conflict (hash) do update set translated_text = excluded.translated_text;
`

mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, sql, 'utf8')
console.log(perFile.join('\n'))
console.log(`\nWrote ${rows.length} unique rows to ${outPath}`)
