-- Secure, atomic referral redemption.
-- Run this migration before deploying the matching Edge Function.

create unique index if not exists profiles_invite_code_unique
  on profiles (upper(invite_code))
  where invite_code is not null and invite_code <> '';

create table if not exists invite_redemptions (
  id uuid primary key default gen_random_uuid(),
  inviter_user_id uuid not null references profiles(id) on delete cascade,
  invitee_user_id uuid not null references profiles(id) on delete cascade,
  redeemed_at timestamptz not null default now(),
  constraint invite_redemptions_not_self check (inviter_user_id <> invitee_user_id),
  constraint invite_redemptions_one_inviter_per_user unique (invitee_user_id)
);

create index if not exists invite_redemptions_inviter_idx
  on invite_redemptions (inviter_user_id);
create unique index if not exists invite_redemptions_invitee_unique
  on invite_redemptions (invitee_user_id);

-- The app accesses these tables only through the verified Edge Function.
-- Prevent the public API roles from bypassing its identity and referral checks.
alter table profiles enable row level security;
alter table invite_redemptions enable row level security;
revoke all on table profiles from anon, authenticated;
revoke all on table invite_redemptions from anon, authenticated;

-- Preserve codes generated by the temporary coupon-based invite UI.
do $$
begin
  if to_regclass('public.coupons') is not null then
    execute $migration$
      update profiles p
      set invite_code = upper(c.code)
      from coupons c
      where c.id = p.id
        and (p.invite_code is null or p.invite_code = '')
        and not exists (
          select 1 from profiles other
          where upper(other.invite_code) = upper(c.code)
        )
    $migration$;
  end if;
end $$;

create or replace function redeem_invite_atomic(p_invitee uuid, p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inviter uuid;
  v_count integer;
begin
  select id into v_inviter
  from profiles
  where upper(invite_code) = upper(trim(p_code))
  for update;

  if v_inviter is null then
    return jsonb_build_object('ok', false, 'error', 'invalid code');
  end if;
  if v_inviter = p_invitee then
    return jsonb_build_object('ok', false, 'error', 'cannot redeem your own code');
  end if;

  begin
    insert into invite_redemptions (inviter_user_id, invitee_user_id)
    values (v_inviter, p_invitee);
  exception when unique_violation then
    return jsonb_build_object('ok', false, 'error', 'you already redeemed an invite code');
  end;

  select count(*)::integer into v_count
  from invite_redemptions
  where inviter_user_id = v_inviter;

  if v_count >= 2 then
    update profiles
    set maqtab_unlocked = true
    where id = v_inviter;
  end if;

  return jsonb_build_object(
    'ok', true,
    'redeemedCount', v_count,
    'inviterUnlocked', v_count >= 2
  );
end;
$$;

revoke all on function redeem_invite_atomic(uuid, text) from public;
grant execute on function redeem_invite_atomic(uuid, text) to service_role;
